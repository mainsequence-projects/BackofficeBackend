"""Generate reviewable contracts and a table dictionary directly from code."""

import argparse
import json
from pathlib import Path

from src.backoffice.models.assignment import PersonDocumentSet
from src.backoffice.models.common import (
    BankTransaction,
    DatePeriod,
    Employer,
    EvidenceRegion,
    Money,
    PostalAddress,
)
from src.backoffice.models.document import DocumentInstance, DocumentReview, RawDocumentRef
from src.backoffice.models.document_set import (
    DocumentOption,
    DocumentRequirement,
    DocumentSet,
    RequirementCondition,
)
from src.backoffice.models.person import Person
from src.backoffice.policies import new_account_requirements
from src.backoffice.schemas.catalog import document_schema
from src.backoffice.schemas.registry import DOCUMENT_MODELS

ROOT = Path(__file__).resolve().parents[1]


def schema_type(schema: dict) -> str:
    if "$ref" in schema:
        return schema["$ref"].rsplit("/", 1)[-1]
    if "anyOf" in schema or "oneOf" in schema:
        return " or ".join(
            schema_type(item) for item in schema.get("anyOf", schema.get("oneOf", []))
        )
    if "enum" in schema:
        return ", ".join(str(item) for item in schema["enum"])
    if "const" in schema:
        return repr(schema["const"])
    if schema.get("type") == "array":
        return f"list[{schema_type(schema['items'])}]"
    return schema.get("format", schema.get("type", "any"))


def model_reference() -> str:
    models = [
        PostalAddress,
        Money,
        DatePeriod,
        Employer,
        BankTransaction,
        EvidenceRegion,
        *DOCUMENT_MODELS.values(),
        Person,
        RawDocumentRef,
        DocumentReview,
        DocumentInstance,
        RequirementCondition,
        DocumentOption,
        DocumentRequirement,
        DocumentSet,
        PersonDocumentSet,
    ]
    lines = [
        "# Pydantic model reference",
        "",
        "Generated by `python -m scripts.export_contracts`. Edit field metadata in code.",
        "",
        "Required means required in a complete payload. Conditional validators and draft behavior are explained in the [foundation guide](foundation.md). Read-only fields appear in output only.",
        "",
    ]
    for model in models:
        schema = model.model_json_schema(mode="serialization")
        lines.extend(
            [
                f"## `{model.__name__}`",
                "",
                f"Source: `{model.__module__}`.",
                "",
                "| Field | Type | Required | Description |",
                "| --- | --- | --- | --- |",
            ]
        )
        for name, field in schema["properties"].items():
            required = (
                "Read-only"
                if field.get("readOnly")
                else ("Yes" if name in schema.get("required", []) else "No")
            )
            lines.append(
                f"| `{name}` | `{schema_type(field)}` | {required} | {field['description'].replace('|', r'\|')} |"
            )
        lines.append("")
    return "\n".join(lines)


def generated_files() -> dict[Path, str]:
    # Keep MetaTables imports out of Pydantic-only consumers.
    from src.backoffice.tables import metatable_models

    files = {Path("docs/model-reference.md"): model_reference()}
    for kind, version in DOCUMENT_MODELS:
        contract = document_schema(kind, version).model_dump(mode="json")
        files[Path(f"schemas/documents/{kind}/v{version}.json")] = (
            json.dumps(contract, indent=2, ensure_ascii=False) + "\n"
        )
    files[Path("schemas/document_sets/new_account_requirements.v1.json")] = (
        new_account_requirements().model_dump_json(indent=2) + "\n"
    )
    lines = [
        "# MetaTable dictionary",
        "",
        "Generated by `python -m scripts.export_contracts`. Edit table metadata in code.",
        "",
        "These are authored contracts; generating this dictionary does not register or migrate a runtime.",
        "",
    ]
    for model in metatable_models():
        table = model.__table__
        lines.extend(
            [
                f"## `{model.__metatable_identifier__}`",
                "",
                model.__metatable_description__,
                "",
                f"Namespace: `backoffice`. Physical name: `{table.name}`.",
                "",
                "| Column | Type | Nullable | Label | Description |",
                "| --- | --- | --- | --- | --- |",
            ]
        )
        for col in table.columns:
            description = col.info["description"].replace("|", "\\|")
            lines.append(
                f"| `{col.name}` | `{col.type}` | {'Yes' if col.nullable else 'No'} | {col.info['label']} | {description} |"
            )
        lines.extend(
            [
                "",
                f"Primary key: {', '.join(f'`{col.name}`' for col in table.primary_key.columns)}.",
                "",
            ]
        )
        for fk in sorted(table.foreign_key_constraints, key=lambda item: str(item.name)):
            references = ", ".join(
                f"`{element.parent.name}` → `{element.target_fullname}`" for element in fk.elements
            )
            lines.extend([f"Foreign key: {references}.", ""])
        for constraint in sorted(table.constraints, key=lambda item: str(item.name)):
            if hasattr(constraint, "sqltext"):
                lines.extend([f"Check: `{constraint.sqltext}`.", ""])
            elif type(constraint).__name__ == "UniqueConstraint":
                lines.extend(
                    [f"Unique: {', '.join(f'`{col.name}`' for col in constraint.columns)}.", ""]
                )
    files[Path("docs/metatable-dictionary.md")] = "\n".join(lines)
    return files


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="Fail when generated artifacts differ without changing files.",
    )
    args = parser.parse_args()
    stale = []
    for relative, content in generated_files().items():
        path = ROOT / relative
        if args.check:
            if not path.exists() or path.read_text() != content:
                stale.append(str(relative))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content)
    if stale:
        parser.exit(1, "Outdated generated contracts: " + ", ".join(stale) + "\n")


if __name__ == "__main__":
    main()
