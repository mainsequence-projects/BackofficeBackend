"""KYC Questionnaire canonical document contract."""

from typing import Literal, Self

from pydantic import AwareDatetime, Field, model_validator

from ..common import DocumentModel, Money, NonEmptyStr


class KYCQuestionnaire(DocumentModel):
    """Structured facts from a kyc questionnaire."""

    document_type: Literal["kyc_questionnaire"] = Field(
        default="kyc_questionnaire",
        title="Document type",
        description="Identifies this payload as kyc questionnaire.",
    )
    full_name: NonEmptyStr = Field(
        title="Full name", description="Name supplied by the person completing the questionnaire."
    )
    occupation: NonEmptyStr | None = Field(
        default=None,
        title="Occupation",
        description="Person's declared occupation or principal economic activity.",
    )
    employment_status: NonEmptyStr = Field(
        title="Employment status",
        description="Declared status, such as employed, self-employed, retired, student, or unemployed.",
    )
    account_purpose: NonEmptyStr = Field(
        title="Account purpose",
        description="Person's explanation of the intended use of the account.",
    )
    expected_monthly_inflow: Money = Field(
        title="Expected monthly inflow",
        description="Expected total incoming funds per calendar month, with currency.",
    )
    expected_monthly_outflow: Money = Field(
        title="Expected monthly outflow",
        description="Expected total outgoing funds per calendar month, with currency.",
    )
    source_of_funds: list[NonEmptyStr] = Field(
        min_length=1,
        title="Source of funds",
        description="One or more declared origins of the money expected to enter the account.",
    )
    completed_at: AwareDatetime = Field(
        title="Completed at",
        description="Time the completed submission was recorded; generated by the server for in-application forms.",
    )
    questionnaire_version: NonEmptyStr = Field(
        title="Questionnaire version",
        description="Version of the questionnaire presented to the person.",
    )

    @model_validator(mode="after")
    def nonnegative_expected_flows(self) -> Self:
        if self.expected_monthly_inflow.amount < 0 or self.expected_monthly_outflow.amount < 0:
            raise ValueError("expected monthly flows must not be negative")
        return self
